/**
 * Employee CSV import (Admin → Employees → Import). Pure rules: parsing, row validation, the import run
 * and its summary. Replaces the old screen that waited 1.5 s and reported "120 employees imported"
 * without saving anything.
 *
 * Policy (same as the Add Employee form / create-employee edge function):
 *   required: first_name, last_name, email, joining_date (YYYY-MM-DD), password (>= 8 characters;
 *   the account must change it at first sign-in). Optional: phone, designation, employment_type
 *   (Full Time / Part Time / Contract), department, office (names), role (EMPLOYEE or HR; default EMPLOYEE).
 *   ADMIN accounts are never created by bulk import.
 *   Duplicates: a row whose e-mail already exists (in the company or earlier in the file) is NOT imported
 *   and is reported as a row error. Employee codes are generated by the server.
 *   Rows are created one by one; a partial import is reported as partial, never as a full success.
 *   The file is read in the browser only and is never uploaded or stored.
 */
export const IMPORT_COLUMNS = ['first_name', 'last_name', 'email', 'joining_date', 'password', 'phone', 'designation', 'employment_type', 'department', 'office', 'role'] as const;
export const IMPORT_REQUIRED = ['first_name', 'last_name', 'email', 'joining_date', 'password'] as const;
export const IMPORT_MAX_ROWS = 500;
const EMPLOYMENT_TYPES = ['Full Time', 'Part Time', 'Contract'];
const IMPORTABLE_ROLES = ['EMPLOYEE', 'HR'];

export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [], field = '', inQuotes = false;
  const src = text.replace(/^﻿/, '');
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (inQuotes) {
      if (c === '"') { if (src[i + 1] === '"') { field += '"'; i++; } else inQuotes = false; }
      else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && src[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((v) => v.trim() !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  row.push(field);
  if (row.some((v) => v.trim() !== '')) rows.push(row);
  return rows;
}

export interface Lookup { id: string; name: string }
export interface ImportContext {
  existingEmails: string[];
  departments: Lookup[];
  offices: Lookup[];
  roles: Lookup[];
}
export interface ImportRow {
  line: number;                 // line in the file (header = 1)
  values: Record<string, string>;
  errors: string[];
  payload: Record<string, any> | null;   // what is sent to createEmployee when valid
}
export interface ParsedImport { headerErrors: string[]; rows: ImportRow[]; valid: ImportRow[]; invalid: ImportRow[] }

const norm = (s: string) => s.trim().toLowerCase();
const isDate = (s: string) => /^\d{4}-\d{2}-\d{2}$/.test(s) && !Number.isNaN(Date.parse(`${s}T00:00:00Z`))
  && new Date(`${s}T00:00:00Z`).toISOString().slice(0, 10) === s;

export function validateImport(text: string, ctx: ImportContext): ParsedImport {
  const table = parseCsv(text);
  if (!table.length) return { headerErrors: ['The file is empty.'], rows: [], valid: [], invalid: [] };
  const header = table[0].map((h) => norm(h).replace(/\s+/g, '_'));
  const headerErrors: string[] = [];
  const missing = IMPORT_REQUIRED.filter((c) => !header.includes(c));
  if (missing.length) headerErrors.push(`Missing column(s): ${missing.join(', ')}.`);
  const unknown = header.filter((h) => h && !(IMPORT_COLUMNS as readonly string[]).includes(h));
  if (unknown.length) headerErrors.push(`Unknown column(s): ${unknown.join(', ')}.`);
  if (table.length - 1 > IMPORT_MAX_ROWS) headerErrors.push(`Too many rows (${table.length - 1}); import at most ${IMPORT_MAX_ROWS} at a time.`);
  if (headerErrors.length) return { headerErrors, rows: [], valid: [], invalid: [] };

  const existing = new Set(ctx.existingEmails.map(norm));
  const seen = new Set<string>();
  const find = (list: Lookup[], v: string) => list.find((x) => norm(x.name) === norm(v));
  const rows: ImportRow[] = table.slice(1).map((cells, i) => {
    const values: Record<string, string> = {};
    header.forEach((h, k) => { values[h] = (cells[k] ?? '').trim(); });
    const errors: string[] = [];
    if (cells.length > header.length && cells.slice(header.length).some((c) => c.trim())) errors.push('More values than columns.');
    for (const c of IMPORT_REQUIRED) if (!values[c]) errors.push(`${c} is required.`);
    const email = norm(values.email || '');
    if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) errors.push('email is not a valid address.');
    else if (email && existing.has(email)) errors.push('An employee with this e-mail already exists (not imported).');
    else if (email && seen.has(email)) errors.push('Duplicate e-mail in this file (not imported).');
    if (email) seen.add(email);
    if (values.joining_date && !isDate(values.joining_date)) errors.push('joining_date must be YYYY-MM-DD.');
    if (values.password && values.password.length < 8) errors.push('password must be at least 8 characters.');
    if (values.employment_type && !EMPLOYMENT_TYPES.some((t) => norm(t) === norm(values.employment_type))) errors.push(`employment_type must be one of: ${EMPLOYMENT_TYPES.join(', ')}.`);
    const dept = values.department ? find(ctx.departments, values.department) : null;
    if (values.department && !dept) errors.push(`Unknown department "${values.department}".`);
    const office = values.office ? find(ctx.offices, values.office) : null;
    if (values.office && !office) errors.push(`Unknown office "${values.office}".`);
    const roleName = (values.role || 'EMPLOYEE').toUpperCase();
    const role = find(ctx.roles, roleName);
    if (!IMPORTABLE_ROLES.includes(roleName)) errors.push('role must be EMPLOYEE or HR (administrators are created individually).');
    else if (!role) errors.push(`Role ${roleName} does not exist.`);
    const payload = errors.length ? null : {
      first_name: values.first_name, last_name: values.last_name, email,
      joining_date: values.joining_date, password: values.password,
      phone: values.phone || null, designation: values.designation || null,
      employment_type: values.employment_type ? EMPLOYMENT_TYPES.find((t) => norm(t) === norm(values.employment_type)) : 'Full Time',
      department_id: dept?.id || null, office_id: office?.id || null, role_id: role!.id, status: 'ACTIVE',
    };
    return { line: i + 2, values, errors, payload };
  });
  if (!rows.length) return { headerErrors: ['The file has a header but no employee rows.'], rows, valid: [], invalid: [] };
  return { headerErrors: [], rows, valid: rows.filter((r) => !r.errors.length), invalid: rows.filter((r) => r.errors.length) };
}

export interface ImportResult { created: { line: number; email: string; id?: string }[]; failed: { line: number; email: string; message: string }[] }

export async function runEmployeeImport(
  valid: ImportRow[],
  create: (payload: Record<string, any>) => Promise<{ data: any; error: any }>,
  onProgress?: (done: number, total: number) => void,
): Promise<ImportResult> {
  const out: ImportResult = { created: [], failed: [] };
  for (let i = 0; i < valid.length; i++) {
    const r = valid[i];
    try {
      const { data, error } = await create(r.payload!);
      if (error || !data) out.failed.push({ line: r.line, email: r.payload!.email, message: error?.message || 'Not created' });
      else out.created.push({ line: r.line, email: r.payload!.email, id: data.id });
    } catch (e: any) {
      out.failed.push({ line: r.line, email: r.payload!.email, message: e?.message || 'Request failed' });
    }
    onProgress?.(i + 1, valid.length);
  }
  return out;
}

export function importSummary(result: ImportResult, skippedInvalid: number): { status: 'success' | 'partial' | 'failed'; message: string } {
  const c = result.created.length, f = result.failed.length;
  const skipped = skippedInvalid ? ` ${skippedInvalid} row(s) were not imported because of errors in the file.` : '';
  if (c && !f && !skippedInvalid) return { status: 'success', message: `${c} employee${c === 1 ? '' : 's'} imported.` };
  if (!c) return { status: 'failed', message: `No employee was imported.${f ? ` ${f} row(s) were rejected by the server.` : ''}${skipped}` };
  return { status: 'partial', message: `${c} imported, ${f} rejected by the server.${skipped}` };
}

